"""A Comparação as CSV or as a LaTeX (booktabs) table, from `compare()`'s result.

Both read the same dict the page draws, so what is published matches what is shown.
"""
import csv
import io

_TYPE_NAMES = {"simples": "Um trecho", "ponte": "Ponte", "comparacao": "Comparação", "agregacao": "Agregação"}
_LATEX_SPECIALS = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def _number(value: float | None) -> str:
    return "" if value is None else f"{value:.6f}"


def to_csv(result: dict) -> str:
    """One row per item (paired, then other Bases) with the page's columns."""
    metric, others = result["metric"], [m for m in result["metrics"] if m != result["metric"]]
    types = result["by_type"]["types"]
    by_type = {row["id"]: row["cells"] for row in result["by_type"]["rows"]}
    header = [
        "item", "experimento", "base", "chunking", "embedding", "rag", "retriever", "llm",
        "parcial", "linha_de_base", "pareamento", "perguntas", metric,
        "diferenca", "ic_inferior", "ic_superior", "significativa",
        *others, *(f"diferenca_{t}" for t in types),
    ]
    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(header)

    def common(item: dict, pairing: str) -> list:
        return [
            item["id"], item["experiment_name"], item["base"], item["chunking"], item["embedding"],
            item["rag"], item["retriever"], item["llm"], "sim" if item["partial"] else "não",
            "sim" if item["id"] == result["baseline"] else "não", pairing, item["n"],
        ]

    for item in result["items"]:
        diff = item["diff"]
        cells = by_type.get(item["id"], {})
        writer.writerow([
            *common(item, "pareado"), _number(item["means"].get(metric)),
            _number(diff and diff["mean"]), _number(diff and diff["low"]), _number(diff and diff["high"]),
            "" if diff is None else ("sim" if diff["significant"] else "não"),
            *(_number(item["means"].get(m)) for m in others),
            *(_number(cells[t]["mean"]) if cells.get(t) else "" for t in types),
        ])
    for item in result["other_bases"]:
        ci = item["mean"]
        writer.writerow([
            *common(item, "outra Base"), _number(ci["mean"]), "", _number(ci["low"]),
            _number(ci["high"]), "", *(_number(item["means"].get(m)) for m in others),
            *("" for _ in types),
        ])
    return buffer.getvalue()


def _tex(text: str) -> str:
    return "".join(_LATEX_SPECIALS.get(ch, ch) for ch in str(text))


def _combo(item: dict) -> str:
    """LLM, técnica, Retriever and Índice; LaTeX commands, not Unicode, for · and ×."""
    parts = [_tex(item["llm"]), _tex(item["rag"])]
    if item["rag"] not in ("closed_book", "oracle"):
        parts += [_tex(item["retriever"]),
                  f"{_tex(item['chunking'])}$\\times${_tex(item['embedding'])}"]
    return " \\textperiodcentered{} ".join(parts)


def _diff(cell: dict) -> str:
    star = "*" if cell["significant"] else ""
    return f"{cell['mean']:+.3f}{star}~[{cell['low']:.3f}, {cell['high']:.3f}]"


def _friedman_text(friedman: dict) -> str:
    if "reason" in friedman:
        return f"Friedman não calculado: {_tex(friedman['reason'])}."
    p = "p < 0.001" if friedman["p"] < 0.001 else f"p = {friedman['p']:.3f}"
    return (f"Friedman: $\\chi^2 = {friedman['chi2']:.2f}$, {friedman['df']} graus de liberdade, "
            f"${p}$, sobre {friedman['n']} perguntas.")


def _table(caption: str, columns: str, header: list[str], rows: list[list[str]]) -> list[str]:
    return [
        "\\begin{table}[ht]", "\\centering", "\\small", f"\\caption{{{caption}}}",
        f"\\begin{{tabular}}{{{columns}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule",
        *(" & ".join(row) + " \\\\" for row in rows),
        "\\bottomrule", "\\end{tabular}", "\\end{table}", "",
    ]


def to_latex(result: dict) -> str:
    """Booktabs tables in the campaign paper's format: mean, difference, CI, * when significant."""
    metric = _tex(result["metric"])
    names = {item["id"]: item for item in result["items"]}
    lines = [
        "% Requires \\usepackage{booktabs}. Generated by the Ditto Comparação.",
        *_table(
            f"Comparação contra a Linha de base ({_combo(names[result['baseline']])}), "
            f"Base {_tex(result['base'])}, métrica {metric}. Diferença: média pareada por pergunta, "
            f"IC 95\\% por bootstrap (10.000 reamostragens, semente 0); * quando o IC não cruza zero. "
            f"{_friedman_text(result['friedman'])} Sem correção para comparações múltiplas.",
            "llrrl",
            ["Combinação", "Experimento", "n", "Média", "Diferença [IC 95\\%]"],
            [
                [_combo(item), _tex(item["experiment_name"]), str(item["n"]),
                 f"{item['means'][result['metric']]:.3f}",
                 "Linha de base" if item["diff"] is None else _diff(item["diff"])]
                for item in result["items"]
            ],
        ),
    ]
    types = result["by_type"]["types"]
    if result["by_type"]["rows"]:
        lines += _table(
            f"Diferença contra a Linha de base por tipo de pergunta ({metric}).",
            "l" + "l" * len(types),
            ["Combinação", *(_TYPE_NAMES.get(t, _tex(t)) for t in types)],
            [
                [_combo(names[row["id"]]),
                 *(_diff(row["cells"][t]) if row["cells"].get(t) else "---" for t in types)]
                for row in result["by_type"]["rows"]
            ],
        )
    if result["other_bases"]:
        lines += _table(
            f"Outras Bases (sem pareamento): média de {metric} e IC 95\\% por bootstrap.",
            "lllrl",
            ["Combinação", "Base", "Experimento", "n", "Média [IC 95\\%]"],
            [
                [_combo(item), _tex(item["base"]), _tex(item["experiment_name"]), str(item["n"]),
                 f"{item['mean']['mean']:.3f}~[{item['mean']['low']:.3f}, {item['mean']['high']:.3f}]"]
                for item in result["other_bases"]
            ],
        )
    return "\n".join(lines)
